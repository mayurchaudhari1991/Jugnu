// Chooses what a fresh install starts with, before building:
//   node scripts/use-seed.cjs personal   → your prescription (your own phone)
//   node scripts/use-seed.cjs shared     → empty, for friends (no personal data in the app at all)
const fs = require('fs');
const path = require('path');

const kind = process.argv[2];
const dir = path.join(__dirname, '..', 'src', 'core');
const out = path.join(dir, 'seed-data.ts');
const HEADER = "// GENERATED by scripts/use-seed.cjs: the data a fresh install starts with. Don't edit; edit seed-personal.ts.\n";

if (kind === 'personal') {
  const src = fs.readFileSync(path.join(dir, 'seed-personal.ts'), 'utf8');
  fs.writeFileSync(out, HEADER + src.split('\n').filter((l, i) => i > 1).join('\n'));
} else if (kind === 'shared') {
  fs.writeFileSync(
    out,
    `${HEADER}import type { Item, Routine } from './types';

export const SEED_KIND: 'personal' | 'shared' = 'shared';
export const SEED_ITEMS: Item[] = [];
export const SEED_ROUTINES: Routine[] = [];
`,
  );
} else {
  console.error('usage: node scripts/use-seed.cjs personal|shared');
  process.exit(1);
}
console.log(`seed: ${kind}`);
